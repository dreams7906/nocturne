			LineHeight = 1.15,
			Parent = row,
		})
		ctx.Theme:Bind(label, { TextColor3 = style == "Text" and "Text" or (style == "Muted" and "TextMuted" or "TextDim") })
		Util.padding(row, 3, 0)
