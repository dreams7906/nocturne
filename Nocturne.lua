			local bar = Util.frame({
				Size = UDim2.fromOffset(1, 11),
				BackgroundTransparency = 0,
				LayoutOrder = order,
				ZIndex = 2,
				Parent = parent,
			})
			theme:Bind(bar, { BackgroundColor3 = "BorderStrong" })
			return bar
		end

