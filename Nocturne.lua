	function Section:AddToggle(flag, opts)
		flag, opts = args(self, flag, opts)
		local section = self
		local el
		local toggle = self.Container:Toggle({
			Text = opts.Title or opts.Text,
			Default = opts.Default == true,
			Flag = opts.Save ~= false and flag or nil,
			Tooltip = opts.Tooltip or opts.Description,
			Style = opts.Style,
			Callback = function(value)
				changed(el, value, opts.Callback)
			end,
		})
		el = element(self, flag, opts.Default == true, toggle.Row)
		el.Default = opts.Default == true
		function el:SetValue(value)
			toggle:Set(value)
		end
		function el:Reset()
			toggle:Set(self.Default)
		end
		-- Presses flip the toggle ("Toggle") or hold it on while held ("Hold").
		function el:AddKeybind(keyFlag, keyOpts)
			if type(keyFlag) == "table" or keyFlag == nil then
				keyOpts = keyFlag or {}
				keyFlag = keyOpts.Flag or (flag .. "Key")
			end
			keyOpts = keyOpts or {}
			local keyEl
			local pill = toggle:AddKeybind({
				Default = keyName(keyOpts.Default),
				Flag = keyOpts.Save ~= false and keyFlag or nil,
				Mode = keyOpts.Mode,
				Changed = function(key)
					changed(keyEl, key, keyOpts.ChangedCallback)
				end,
			})
			keyEl = element(section, keyFlag, pill:Get(), nil)
			function keyEl:SetValue(key)
				pill:Set(keyName(key))
				changed(keyEl, pill:Get())
			end
			return self
		end
		function el:AddColorPicker(colorFlag, colorOpts)
			if type(colorFlag) == "table" or colorFlag == nil then
				colorOpts = colorFlag or {}
				colorFlag = colorOpts.Flag or (flag .. "Color")
			end
			colorOpts = colorOpts or {}
			local colorEl
			local swatch = toggle:AddColor({
				Default = colorOpts.Default,
				Flag = colorOpts.Save ~= false and colorFlag or nil,
				Callback = function(color)
					changed(colorEl, color, colorOpts.Callback)
				end,
			})
			colorEl = element(section, colorFlag, swatch:Get(), nil)
			function colorEl:SetValue(color)
				swatch:Set(color)
			end
			return self
		end
		el.AddColor = el.AddColorPicker
		return el
	end

	function Section:AddSwitch(flag, opts)
		flag, opts = args(self, flag, opts)
		local copy = table.clone(opts)
		copy.Style = "Switch"
		return self:AddToggle(flag, copy)
	end

	function Section:AddSlider(flag, opts)
		flag, opts = args(self, flag, opts)
		local step = opts.Increment or opts.Step or (opts.Rounding and 10 ^ -opts.Rounding) or 1
		local min, max = opts.Min or 0, opts.Max or 100
		local default = math.clamp(opts.Default or min, min, max)
		local el
		local slider = self.Container:Slider({
			Text = opts.Title or opts.Text,
			Min = min,
			Max = max,
			Step = step,
			Default = default,
			Suffix = opts.Suffix,
			Flag = opts.Save ~= false and flag or nil,
			Tooltip = opts.Tooltip or opts.Description,
			Callback = function(value)
				changed(el, value, opts.Callback)
			end,
		})
		el = element(self, flag, slider:Get(), lastRow(self.Container))
		el.Default = default
		function el:SetValue(value)
			slider:Set(value)
		end
		function el:Reset()
			slider:Set(self.Default)
		end
		return el
	end

	function Section:AddDropdown(flag, opts)
		flag, opts = args(self, flag, opts)
		local values = opts.Values or opts.Options or {}
		local default = opts.Default
		if type(default) == "number" and not opts.Multi then
			default = values[default]
		end
		local el
		local dropdown = self.Container:Dropdown({
			Text = opts.Title or opts.Text,
			Options = values,
			Default = default,
			Multi = opts.Multi,
			AllowNull = opts.AllowNull,
			Placeholder = opts.Placeholder,
			Flag = opts.Save ~= false and flag or nil,
			Tooltip = opts.Tooltip or opts.Description,
			Callback = function(value)
				changed(el, value, opts.Callback)
			end,
		})
		el = element(self, flag, dropdown:Get(), lastRow(self.Container))
		function el:SetValue(value)
			dropdown:Set(value)
		end
		function el:SetValues(newValues)
			values = table.clone(newValues)
			dropdown:SetOptions(values, true)
			el.Value = dropdown:Get()
			Library.Flags[flag] = el.Value
		end
		el.Refresh = el.SetValues
		function el:AddValue(value)
			table.insert(values, value)
			el:SetValues(values)
		end
		function el:RemoveValue(value)
			local index = table.find(values, value)
			if index then
				table.remove(values, index)
				el:SetValues(values)
			end
		end
		function el:GetSelected()
			return dropdown:GetSelected()
		end
		return el
	end

	function Section:AddInput(flag, opts)
		flag, opts = args(self, flag, opts)
		local function parse(text)
			if not opts.Numeric then
				return text
			end
			local number = tonumber(text)
			if not number then
				return nil
			end
			return math.clamp(number, opts.Min or -math.huge, opts.Max or math.huge)
		end
		local el
		local input
		input = self.Container:Input({
			Text = opts.Title or opts.Text,
			Placeholder = opts.Placeholder,
			Default = opts.Default ~= nil and tostring(opts.Default) or "",
			MaxLength = opts.MaxLength,
			Live = not opts.Finished,
			Flag = opts.Save ~= false and flag or nil,
			Tooltip = opts.Tooltip or opts.Description,
			Callback = function(text)
				local value = parse(text)
				if value == nil then
					if opts.Numeric and text ~= "" and text ~= "-" then
						input:Set(tostring(el.Value or ""), true)
					end
					return
				end
				if opts.Numeric and tostring(value) ~= text and not opts.Finished then
					return
				end
				changed(el, value, opts.Callback)
			end,
		})
		el = element(self, flag, parse(input:Get()), lastRow(self.Container))
		function el:SetValue(value)
			input:Set(tostring(value))
		end
		return el
	end

	function Section:AddKeybind(flag, opts)
		flag, opts = args(self, flag, opts)
		local mode = opts.Mode or "Toggle"
		local state = mode == "Always"
		local clicks = {}
		local el
		local function setState(value)
			if state == value then
				return
			end
			state = value
			call(opts.Callback, state)
		end
		local pill = self.Container:Keybind({
			Text = opts.Title or opts.Text,
			Default = keyName(opts.Default),
			Flag = opts.Save ~= false and flag or nil,
			Tooltip = opts.Tooltip or opts.Description,
			Callback = function()
				for _, fn in ipairs(clicks) do
					call(fn)
				end
				if mode == "Toggle" then
					setState(not state)
				elseif mode == "Hold" then
					setState(true)
				end
			end,
			OnRelease = function()
				if mode == "Hold" then
					setState(false)
				end
			end,
			Changed = function(key)
				changed(el, key, opts.ChangedCallback)
			end,
		})
		el = element(self, flag, pill:Get(), lastRow(self.Container))
		function el:SetValue(key, newMode)
			if newMode then
				mode = newMode
				state = mode == "Always"
			end
			pill:Set(keyName(key))
		end
		function el:GetState()
			return state
		end
		function el:OnClick(fn)
			table.insert(clicks, fn)
			return self
		end
		return el
	end

	function Section:AddColorPicker(flag, opts)
		flag, opts = args(self, flag, opts)
		local el
		local swatch = self.Container:ColorPicker({
			Text = opts.Title or opts.Text,
			Default = opts.Default or Color3.new(1, 1, 1),
			Flag = opts.Save ~= false and flag or nil,
			Tooltip = opts.Tooltip or opts.Description,
			Callback = function(color)
				changed(el, color, opts.Callback)
			end,
		})
		el = element(self, flag, swatch:Get(), lastRow(self.Container))
		function el:SetValue(color)
			swatch:Set(color)
		end
		return el
	end

	--[[
		Section:AddButton({ Title, Callback, Confirm = true, Style = "Primary" | "Danger", Icon })
			:AddButton({ ... })   -- adds another button to the same row
	]]
	function Section:AddButton(opts)
		opts = opts or {}
		local container = self.Container
		local group = { list = {}, row = nil }

		local function build()
			local order
			if group.row then
				order = group.row.LayoutOrder
				group.row:Destroy()
			end
			local specs = {}
			local buttons
			for index, spec in ipairs(group.list) do
				local armedAt = 0
				specs[index] = {
					Text = spec.Title or spec.Text,
					Icon = spec.Icon,
					Style = spec.Style,
					Tooltip = spec.Tooltip,
					Callback = function()
						if spec.Confirm then
							local button = buttons[index]
							if os.clock() - armedAt > 2.5 then
								armedAt = os.clock()
								button:SetText(type(spec.Confirm) == "string" and spec.Confirm or "Click again to confirm")
								task.delay(2.5, function()
									if os.clock() - armedAt >= 2.4 and button.Root.Parent then
										button:SetText(spec.Title or spec.Text)
									end
								end)
								return
							end
							armedAt = 0
							button:SetText(spec.Title or spec.Text)
						end
						call(spec.Callback)
					end,
				}
			end
			buttons = container:Buttons(specs)
			group.row = lastRow(container)
			if order then
				group.row.LayoutOrder = order
			end
		end

		local handle = {}
		function handle:AddButton(nextOpts)
			table.insert(group.list, nextOpts or {})
			build()
			return handle
		end
		function handle:SetVisible(visible)
			group.row.Visible = visible
		end
		table.insert(group.list, opts)
		build()
		return handle
	end

	function Section:AddLabel(text, style)
		local label = self.Container:Label(text, style)
		local row = lastRow(self.Container)
		return {
			SetText = function(_, value)
				label:Set(value)
			end,
			SetVisible = function(_, visible)
				row.Visible = visible
			end,
		}
	end

	function Section:AddParagraph(opts)
		opts = opts or {}
		local title, content = opts.Title or "", opts.Content or opts.Text or ""
		local paragraph = self.Container:Paragraph(title, content)
		local row = lastRow(self.Container)
		return {
			SetTitle = function(_, value)
				paragraph:Set(value, nil)
			end,
			SetContent = function(_, value)
				paragraph:Set(nil, value)
			end,
			SetVisible = function(_, visible)
				row.Visible = visible
			end,
		}
	end

	function Section:AddInfo(opts)
		return self.Container:Info({ Text = opts.Title or opts.Text, Value = opts.Value, Accent = opts.Accent })
	end

	function Section:AddDivider(text)
		self.Container:Divider(text)
	end

	return Library
end

__node("Nocturne.Navigation.Page")
__modules["Nocturne.Navigation.Page"] = function(script, require)
	--[[
		Page
		One main section of the window (Combat, Visuals, ...). A page is a
		CanvasGroup so it can cross-fade, with a scrolling two-column body.

		app:Page({ Name = "Combat", Icon = "combat", Columns = 2 }) -> page
			page:Section({ Title, Side = "Left" | "Right", Tabs })
	]]

	local Util = require(script.Parent.Parent.Core.Util)
	local Section = require(script.Parent.Parent.Components.Section)

	local Page = {}
	Page.__index = Page

	local GAP = 10

	function Page.new(ctx, parent, opts)
		local self = setmetatable({
			ctx = ctx,
			Name = opts.Name or "Page",
			Icon = opts.Icon or "misc",
			Description = opts.Description,
			_orders = { Left = 0, Right = 0 },
		}, Page)

		local canvas = Util.new("CanvasGroup", {
			Name = "Page_" .. self.Name,
			Size = UDim2.fromScale(1, 1),
			BackgroundTransparency = 1,
			BorderSizePixel = 0,
			Visible = false,
			Parent = parent,
		})

		local scroller = Util.new("ScrollingFrame", {
			Name = "Scroller",
			Size = UDim2.fromScale(1, 1),
			BackgroundTransparency = 1,
			BorderSizePixel = 0,
			ScrollBarThickness = 3,
			ScrollingDirection = Enum.ScrollingDirection.Y,
			AutomaticCanvasSize = Enum.AutomaticSize.Y,
			CanvasSize = UDim2.new(),
			VerticalScrollBarInset = Enum.ScrollBarInset.None,
			Parent = canvas,
		})
		ctx.Theme:Bind(scroller, { ScrollBarImageColor3 = "BorderStrong" })
		Util.padding(scroller, 12, 14, 14, 12)

		local columns = Util.frame({
			Name = "Columns",
			Size = UDim2.new(1, 0, 0, 0),
			AutomaticSize = Enum.AutomaticSize.Y,
			Parent = scroller,
		})
		Util.list(columns, { FillDirection = Enum.FillDirection.Horizontal, Padding = GAP })

		local single = opts.Columns == 1
		local function column(name, order)
			local frame = Util.frame({
				Name = name,
				Size = single and UDim2.new(1, 0, 0, 0) or UDim2.new(0.5, -GAP / 2, 0, 0),
				AutomaticSize = Enum.AutomaticSize.Y,
				LayoutOrder = order,
				Parent = columns,
			})
			Util.list(frame, { Padding = GAP })
			return frame
		end
		self.Left = column("Left", 1)
		self.Right = single and self.Left or column("Right", 2)

		-- Floating popups would drift away from their fields while scrolling.
		scroller:GetPropertyChangedSignal("CanvasPosition"):Connect(function()
			ctx.Popups:CloseAll()
		end)

		self.Canvas = canvas
		self.Scroller = scroller
		return self
	end

	function Page:Section(opts)
		opts = opts or {}
		local side = opts.Side == "Right" and "Right" or "Left"
		self._orders[side] += 1
		return Section.new(self.ctx, side == "Right" and self.Right or self.Left, opts, self._orders[side])
	end

	return Page
end

__node("Nocturne.Navigation.Toolbar")
__modules["Nocturne.Navigation.Toolbar"] = function(script, require)
	--[[
		Toolbar
		Floating glass dock at the top centre of the screen. One icon per page.

		- Clicking an icon opens the window on that page.
		- Clicking the active icon again collapses the window; the toolbar stays.
		- A soft highlight pill glides between icons and carries an accent dot.
		- Hover lifts the icon slightly and shows a small label under the dock.
	]]

	local Util = require(script.Parent.Parent.Core.Util)
	local Signal = require(script.Parent.Parent.Core.Signal)
	local Motion = require(script.Parent.Parent.Animations.Motion)
	local Icons = require(script.Parent.Parent.Icons.Icons)

	local Toolbar = {}
	Toolbar.__index = Toolbar

	local BUTTON = 34
	local GAP = 4
	local PAD = 6
	local TOP = 12
	local ICON = 18

	function Toolbar.new(ctx)
		local theme = ctx.Theme
		local self = setmetatable({
			ctx = ctx,
			Items = {},
			Active = nil,
			Clicked = Signal.new(),
		}, Toolbar)

		local surface = Util.surface(ctx, {
			Name = "Toolbar",
			Radius = 15,
			AnchorPoint = Vector2.new(0.5, 0),
			Position = UDim2.new(0.5, 0, 0, TOP),
			Size = UDim2.fromOffset(PAD * 2, BUTTON + PAD * 2),
			ShadowLayers = 6,
			ShadowSpread = 3,
			ShadowOffset = 6,
			ShadowTransparency = 0.92,
			GlossStrength = 0.16,
			FillTransparency = function(tokens)
				return math.clamp(tokens.Transparency + 0.08, 0, 0.6)
			end,
			ZIndex = 20,
			Parent = ctx.Gui,
		})
		self.Surface, self.Holder = surface, surface.Holder
		self.Scale = Util.new("UIScale", { Parent = surface.Holder })

		-- Highlight pill that slides to the active icon.
		local indicator = Util.frame({
			Name = "Indicator",
			Position = UDim2.fromOffset(PAD, PAD),
			Size = UDim2.fromOffset(BUTTON, BUTTON),
			BackgroundTransparency = 1,
			ZIndex = 2,
			Parent = surface.Body,
		})
		Util.corner(indicator, 10)
		local indicatorStroke = Util.stroke(indicator, { Transparency = 1 })
		theme:Bind(indicator, { BackgroundColor3 = "Hover" })
		theme:Bind(indicatorStroke, { Color = "BorderStrong" })
		local indicatorGloss = Util.gloss(indicator, 0.22)
		ctx:RegisterGloss(indicatorGloss)

		local dot = Util.frame({
			Name = "Dot",
			AnchorPoint = Vector2.new(0.5, 1),
			Position = UDim2.new(0.5, 0, 1, -3),
			Size = UDim2.fromOffset(4, 4),
			BackgroundTransparency = 1,
			ZIndex = 4,
			Parent = indicator,
		})
		Util.corner(dot, UDim.new(1, 0))
		theme:Bind(dot, { BackgroundColor3 = "Accent" })
		self.Indicator, self.IndicatorStroke, self.Dot = indicator, indicatorStroke, dot

		local row = Util.frame({
			Name = "Buttons",
			Position = UDim2.fromOffset(PAD, PAD),
			Size = UDim2.new(1, -PAD * 2, 0, BUTTON),
			ZIndex = 3,
			Parent = surface.Body,
		})
		Util.list(row, {
			FillDirection = Enum.FillDirection.Horizontal,
			Padding = GAP,
			VerticalAlignment = Enum.VerticalAlignment.Center,
		})
		self.Row = row

		-- Hover label shown beneath the dock.
		local hint = Util.text({
			Name = "Hint",
			AnchorPoint = Vector2.new(0.5, 0),
			Position = UDim2.new(0, 0, 1, 10),
			AutomaticSize = Enum.AutomaticSize.X,
			Size = UDim2.fromOffset(0, 20),
			TextSize = 11,
			FontFace = Util.Fonts.SemiBold,
			TextXAlignment = Enum.TextXAlignment.Center,
			BackgroundTransparency = 1,
			TextTransparency = 1,
			ZIndex = 30,
			Parent = surface.Holder,
		})
		Util.corner(hint, 6)
		Util.padding(hint, 0, 8)
		local hintStroke = Util.stroke(hint, { Transparency = 1 })
		theme:Bind(hint, { BackgroundColor3 = "Elevated", TextColor3 = "TextDim" })
		theme:Bind(hintStroke, { Color = "BorderStrong" })
		self.Hint, self.HintStroke = hint, hintStroke
		self._hintToken = 0

		theme.Changed:Connect(function(instant)
			self:_render(instant)
		end)

		-- Entrance: drop in from above.
		surface.Holder.Position = UDim2.new(0.5, 0, 0, TOP - 14)
		surface.SetAlpha(1, "Instant")
		task.defer(function()
			Motion.tween(surface.Holder, "Slow", { Position = UDim2.new(0.5, 0, 0, TOP) })
			surface.SetAlpha(0, "Slow")
		end)
		return self
	end

	function Toolbar:Bottom()
		return (TOP + BUTTON + PAD * 2) * self.Scale.Scale
	end

	function Toolbar:SetScale(scale)
		self.Scale.Scale = scale
	end

	function Toolbar:_offset(index)
		return PAD + (index - 1) * (BUTTON + GAP)
	end

	function Toolbar:_render(instant)
		local t = self.ctx.Theme.Tokens
		for _, item in ipairs(self.Items) do
			local active = item.Page == self.Active
			local color = active and t.Text or (item.Hovered and t.TextDim or t.TextMuted)
			Icons.tween(item.Icon, instant and "Instant" or "Fast", color)
		end
	end

	function Toolbar:_showHint(item)
		self._hintToken += 1
		local hint = self.Hint
		hint.Text = item.Page.Name
		local x = self:_offset(item.Index) + BUTTON / 2
		hint.Position = UDim2.new(0, x, 1, 6)
		Motion.tween(hint, "Fast", {
			Position = UDim2.new(0, x, 1, 10),
			BackgroundTransparency = 0.04,
			TextTransparency = 0,
		})
		Motion.tween(self.HintStroke, "Fast", { Transparency = 0.25 })
	end

	function Toolbar:_hideHint()
		self._hintToken += 1
		Motion.tween(self.Hint, "Fast", { BackgroundTransparency = 1, TextTransparency = 1 })
		Motion.tween(self.HintStroke, "Fast", { Transparency = 1 })
	end

	function Toolbar:AddItem(page)
		local index = #self.Items + 1
		local button = Util.button({
			Name = page.Name,
			Size = UDim2.fromOffset(BUTTON, BUTTON),
			LayoutOrder = index,
			ZIndex = 3,
			Parent = self.Row,
		})
		local scale = Util.new("UIScale", { Parent = button })
		local icon = Icons.create(page.Icon, ICON, self.ctx.Theme.Tokens.TextMuted, {
			AnchorPoint = Vector2.new(0.5, 0.5),
			Position = UDim2.fromScale(0.5, 0.5),
			ZIndex = 3,
			Parent = button,
		})
		local item = { Page = page, Button = button, Icon = icon, Scale = scale, Index = index, Hovered = false }
		table.insert(self.Items, item)

		button.MouseEnter:Connect(function()
			item.Hovered = true
			Motion.tween(scale, "Fast", { Scale = 1.08 })
			self:_render(false)
			self:_showHint(item)
		end)
		button.MouseLeave:Connect(function()
			item.Hovered = false
			Motion.tween(scale, "Normal", { Scale = 1 })
			self:_render(false)
			self:_hideHint()
		end)
		button.MouseButton1Down:Connect(function()
			Motion.tween(scale, "Micro", { Scale = 0.9 })
		end)
		button.MouseButton1Up:Connect(function()
			Motion.tween(scale, "Normal", { Scale = item.Hovered and 1.08 or 1 })
		end)
		button.Activated:Connect(function()
			self.Clicked:Fire(page)
		end)

		local width = PAD * 2 + index * BUTTON + (index - 1) * GAP
		self.Holder.Size = UDim2.fromOffset(width, BUTTON + PAD * 2)
		self:_render(true)
		return item
	end

	function Toolbar:SetActive(page)
		self.Active = page
		local item
		for _, candidate in ipairs(self.Items) do
			if candidate.Page == page then
				item = candidate
			end
		end
		local indicator = self.Indicator
		if item then
			local target = UDim2.fromOffset(self:_offset(item.Index), PAD)
			self._lastIndex = item.Index
			if not self._shown then
				-- Appear in place rather than sliding in from the last position.
				indicator.Size = UDim2.fromOffset(BUTTON - 6, BUTTON - 6)
				indicator.Position = UDim2.fromOffset(self:_offset(item.Index) + 3, PAD + 3)
			end
			Motion.tween(indicator, "Smooth", {
				Position = target,
				Size = UDim2.fromOffset(BUTTON, BUTTON),
				BackgroundTransparency = 0,
			})
			Motion.tween(self.IndicatorStroke, "Smooth", { Transparency = 0.35 })
			Motion.tween(self.Dot, "Smooth", { BackgroundTransparency = 0 })
			self._shown = true
		elseif self._shown then
			self._shown = false
			Motion.tween(indicator, "Normal", {
				BackgroundTransparency = 1,
				Size = UDim2.fromOffset(BUTTON - 6, BUTTON - 6),
				Position = UDim2.fromOffset(self:_offset(self._lastIndex or 1) + 3, PAD + 3),
			})
			Motion.tween(self.IndicatorStroke, "Normal", { Transparency = 1 })
			Motion.tween(self.Dot, "Normal", { BackgroundTransparency = 1 })
		end
		self:_render(false)
	end

	return Toolbar
end

