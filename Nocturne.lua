local __modules = {}
local __cache = {}
local __nodes = {}

local __Node = {}
__Node.__index = function(node, key)
	local method = rawget(__Node, key)
	if method then
		return method
	end
	local child = node.__children[key]
	if child then
		return child
	end
	error(("%s is not a valid member of %s"):format(tostring(key), node.__path), 2)
end
function __Node.FindFirstChild(node, name)
	return node.__children[name]
end
function __Node.WaitForChild(node, name)
	return node.__children[name]
end
function __Node.GetFullName(node)
	return node.__path
end

local function __node(path)
	local existing = __nodes[path]
	if existing then
		return existing
	end
	local parentPath, name = string.match(path, "^(.*)%.([^%.]+)$")
	local node = setmetatable({ Name = name or path, __path = path, __children = {} }, __Node)
	if parentPath then
		local parent = __node(parentPath)
		rawset(node, "Parent", parent)
		parent.__children[node.Name] = node
	end
	__nodes[path] = node
	return node
end

local __require
__require = function(target)
	if type(target) ~= "table" or not rawget(target, "__path") then
		return require(target)
	end
	local path = target.__path
	local cached = __cache[path]
	if cached ~= nil then
		return cached
	end
	local loader = __modules[path]
	if not loader then
		error("Nocturne bundle: no module at " .. path, 2)
	end
	local result = loader(target, __require)
	__cache[path] = result
	return result
end

__node("Nocturne.Animations.Motion")
__modules["Nocturne.Animations.Motion"] = function(script, require)
	--[[
		Motion
		Thin TweenService wrapper with named presets, a global speed multiplier
		and a reduced-motion switch.

		A new tween on a property overrides any running tween on that same
		property (TweenService behaviour), so rapid clicking never stacks
		animations. With reduced motion on, values are applied instantly and a
		zero-length tween is still played to cancel anything in flight.
	]]

	local TweenService = game:GetService("TweenService")

	local Out = Enum.EasingDirection.Out
	local InOut = Enum.EasingDirection.InOut

	local Motion = {
		Reduced = false,
		Speed = 1,
	}

	Motion.Presets = {
		Instant = { 0, Enum.EasingStyle.Linear, Out },
		Micro = { 0.08, Enum.EasingStyle.Quad, Out },
		Fast = { 0.14, Enum.EasingStyle.Quad, Out },
		Normal = { 0.22, Enum.EasingStyle.Quint, Out },
		Smooth = { 0.32, Enum.EasingStyle.Quint, Out },
		Slow = { 0.45, Enum.EasingStyle.Quint, Out },
		Glide = { 0.38, Enum.EasingStyle.Cubic, InOut },
		Linear = { 1, Enum.EasingStyle.Linear, Out },
	}

	local function resolve(preset)
		if type(preset) == "number" then
			return preset, Enum.EasingStyle.Quint, Out
		end
		local data = Motion.Presets[preset] or Motion.Presets.Normal
		return data[1], data[2], data[3]
	end

	function Motion.info(preset)
		local duration, style, direction = resolve(preset)
		if Motion.Reduced then
			duration = 0
		else
			duration /= math.max(Motion.Speed, 0.05)
		end
		return TweenInfo.new(duration, style, direction)
	end

	-- Tweens `props` on `instance`. Returns the Tween (already playing).
	function Motion.tween(instance, preset, props, onComplete)
		local info = Motion.info(preset)
		if info.Time <= 0 then
			for key, value in pairs(props) do
				instance[key] = value
			end
		end
		local tween = TweenService:Create(instance, info, props)
		if onComplete then
			tween.Completed:Once(function(state)
				if state == Enum.PlaybackState.Completed then
					onComplete()
				end
			end)
		end
		tween:Play()
		return tween
	end

	-- Linear tween with an explicit duration that ignores reduced motion
	-- (used for timers such as notification progress bars).
	function Motion.timer(instance, duration, props)
		local tween = TweenService:Create(instance, TweenInfo.new(duration, Enum.EasingStyle.Linear), props)
		tween:Play()
		return tween
	end

	return Motion
end

__node("Nocturne.App")
__modules["Nocturne.App"] = function(script, require)
	--[[
		App
		Low-level application object: ScreenGui, theme, toolbar, window, pages,
		overlays and configs. The public Library API (init.luau) wraps this;
		use it directly only if you want the raw component calls.

		local app = App.new({ Title = "Nocturne", Theme = "Midnight" })
		local page = app:Page({ Name = "Combat", Icon = "combat" })
		page:Section({ Title = "Feedback" }):Toggle({ Text = "Hit markers", Flag = "HitMarkers" })
	]]

	local Players = game:GetService("Players")
	local Lighting = game:GetService("Lighting")
	local SoundService = game:GetService("SoundService")

	local Util = require(script.Parent.Core.Util)
	local Signal = require(script.Parent.Core.Signal)
	local State = require(script.Parent.Core.State)
	local Keybinds = require(script.Parent.Core.Keybinds)
	local Popups = require(script.Parent.Core.Popups)
	local Motion = require(script.Parent.Animations.Motion)
	local Theme = require(script.Parent.Themes.Theme)
	local Presets = require(script.Parent.Themes.Presets)
	local Icons = require(script.Parent.Icons.Icons)
	local Tooltip = require(script.Parent.Components.Tooltip)
	local Notifications = require(script.Parent.Components.Notifications)
	local Window = require(script.Parent.Navigation.Window)
	local Toolbar = require(script.Parent.Navigation.Toolbar)
	local Page = require(script.Parent.Navigation.Page)
	local Watermark = require(script.Parent.Overlays.Watermark)
	local KeybindList = require(script.Parent.Overlays.KeybindList)
	local ConfigManager = require(script.Parent.Config.ConfigManager)

	local Nocturne = {
		Version = "1.0.0",
		Icons = Icons,
		Presets = Presets,
		Motion = Motion,
	}

	local App = {}
	App.__index = App

	function Nocturne.new(options)
		options = options or {}
		local player = Players.LocalPlayer
		local parent = options.Parent or player:WaitForChild("PlayerGui")
		local name = options.Name or "Nocturne"

		local previous = parent:FindFirstChild(name)
		if previous then
			previous:Destroy()
		end

		local gui = Util.new("ScreenGui", {
			Name = name,
			IgnoreGuiInset = true,
			ResetOnSpawn = false,
			ZIndexBehavior = Enum.ZIndexBehavior.Sibling,
			DisplayOrder = options.DisplayOrder or 50,
			Parent = parent,
		})
		local overlay = Util.frame({
			Name = "Overlay",
			Size = UDim2.fromScale(1, 1),
			ZIndex = 100,
			Parent = gui,
		})

		local theme = Theme.new(options.Theme or "Midnight")
		if options.Accent then
			theme.Values.Accent = options.Accent
			theme:Refresh(true)
		end

		-- Shared context handed to every component.
		local ctx = {
			Gui = gui,
			Overlay = overlay,
			Theme = theme,
			State = State.new(),
			Keybinds = Keybinds.new(),
			Popups = Popups.new(),
			NotifyDuration = 4,
			_scale = 1,
			_gloss = {},
		}
		function ctx:GetScale()
			return self._scale
		end
		function ctx:RegisterGloss(instance)
			self._gloss[instance] = true
			instance.Destroying:Once(function()
				self._gloss[instance] = nil
			end)
			local on = self.Theme.Values.Gloss
			if instance:IsA("UIGradient") then
				instance.Enabled = on
			else
				instance.Visible = on
			end
			return instance
		end

		ctx.Tooltip = Tooltip.new(ctx)
		local notifications = Notifications.new(ctx)
		ctx.Notify = function(opts)
			return notifications:Push(opts)
		end

		local self = setmetatable({
			ctx = ctx,
			Gui = gui,
			Theme = theme,
			Flags = ctx.State,
			Keybinds = ctx.Keybinds,
			Notifications = notifications,
			Pages = {},
			UserScale = options.Scale or 1,
			BlurEnabled = options.Blur == true,
			CollapseOnReselect = options.CollapseOnReselect ~= false,
			Opened = Signal.new(),
			Closed = Signal.new(),
			_connections = {},
		}, App)

		self.Toolbar = Toolbar.new(ctx)
		ctx.ToolbarBottom = function()
			return self.Toolbar:Bottom()
		end
		self.Window = Window.new(ctx, options)
		self.Watermark = Watermark.new(ctx, options)
		self.KeybindList = KeybindList.new(ctx)
		self.Configs = ConfigManager.new(ctx.State)

		self.Toolbar.Clicked:Connect(function(page)
			self:_fromToolbar(page)
		end)
		self.Window.PageChanged:Connect(function(page)
			if self.Window.IsOpen then
				self.Toolbar:SetActive(page)
			end
		end)
		self.Window.Closed:Connect(function()
			self.Toolbar:SetActive(nil)
			self:_applyBlur(false)
			self.Closed:Fire()
		end)

		self._menuBind = ctx.Keybinds:Register({
			Name = "Menu",
			Key = options.MenuKey and (typeof(options.MenuKey) == "EnumItem" and options.MenuKey.Name or options.MenuKey)
				or "RightControl",
			Locked = true,
			OnPress = function()
				self:Toggle()
			end,
		})

		notifications:SetScale(1)
		table.insert(self._connections, gui:GetPropertyChangedSignal("AbsoluteSize"):Connect(function()
			self:_applyScale()
		end))
		task.defer(function()
			self:_applyScale()
		end)

		return self
	end

	-- Navigation ----------------------------------------------------------------

	function App:Page(opts)
		local page = Page.new(self.ctx, self.Window.PageHolder, opts)
		table.insert(self.Pages, page)
		self.Window:AddPage(page)
		self.Toolbar:AddItem(page)
		if #self.Pages == 1 then
			self.Window:Select(page, true)
		end
		return page
	end

	function App:GetPage(name)
		for _, page in ipairs(self.Pages) do
			if page.Name == name then
				return page
			end
		end
		return nil
	end

	function App:_fromToolbar(page)
		local window = self.Window
		if window.IsOpen and window.Current == page and not window.Minimized then
			if self.CollapseOnReselect then
				self:Close()
			end
			return
		end
		if window.Minimized then
			window:SetMinimized(false)
		end
		window:Select(page)
		self:Open()
	end

	function App:SelectPage(name)
		local page = type(name) == "table" and name or self:GetPage(name)
		if page then
			self.Window:Select(page)
		end
	end

	function App:Open(pageName)
		if pageName then
			self:SelectPage(pageName)
		end
		if self.Window.IsOpen then
			return
		end
		self.Window:Open()
		self.Toolbar:SetActive(self.Window.Current)
		self:_applyBlur(true)
		self.Opened:Fire()
	end

	function App:Close()
		self.Window:Close()
	end

	function App:Toggle()
		if self.Window.IsOpen then
			self:Close()
		else
			self:Open()
		end
	end

	function App:IsOpen()
		return self.Window.IsOpen
	end

	function App:Notify(opts)
		return self.ctx.Notify(opts)
	end

	-- Appearance ----------------------------------------------------------------

	function App:SetTheme(name)
		self.Theme:SetPreset(name)
	end

	function App:SetAccent(color)
		self.Theme:SetAccent(color)
	end

	function App:SetTransparency(value)
		self.Theme:Set("Transparency", math.clamp(value, 0, 0.6))
	end

	function App:SetGloss(enabled)
		self.Theme:Set("Gloss", enabled)
		for instance in pairs(self.ctx._gloss) do
			if instance:IsA("UIGradient") then
				instance.Enabled = enabled
			else
				instance.Visible = enabled
			end
		end
	end

	function App:SetReducedMotion(enabled)
		Motion.Reduced = enabled
	end

	function App:SetAnimationSpeed(speed)
		Motion.Speed = math.clamp(speed, 0.25, 3)
	end

	function App:SetScale(scale)
		self.UserScale = math.clamp(scale, 0.6, 1.4)
		self:_applyScale()
	end

	-- Fits the window on small screens (phones) on top of the user's choice.
	function App:_applyScale()
		local viewport = self.Gui.AbsoluteSize
		if viewport.X <= 0 or viewport.Y <= 0 then
			return
		end
		local fit = math.min((viewport.X - 32) / Window.Width, (viewport.Y - 96) / Window.Height, 1)
		local scale = self.UserScale * math.clamp(fit, 0.45, 1)
		local chrome = self.UserScale * math.clamp(viewport.X / 520, 0.7, 1)
		self.ctx._scale = scale
		self.Window:SetScale(scale)
		self.Toolbar:SetScale(chrome)
		self.Notifications:SetScale(chrome)
		self.Watermark:SetScale(chrome)
		self.KeybindList:SetScale(chrome)
		self.ctx.Popups:CloseAll()
	end

	function App:SetBlur(enabled)
		self.BlurEnabled = enabled
		self:_applyBlur(enabled and self.Window.IsOpen)
	end

	function App:_applyBlur(on)
		if not self.BlurEnabled then
			on = false
		end
		local blur = self._blur
		if on then
			if not blur then
				blur = Instance.new("BlurEffect")
				blur.Name = "NocturneBlur"
				blur.Size = 0
				blur.Parent = Lighting
				self._blur = blur
			end
			Motion.tween(blur, "Smooth", { Size = 12 })
		elseif blur then
			Motion.tween(blur, "Normal", { Size = 0 }, function()
				if self._blur == blur and not (self.BlurEnabled and self.Window.IsOpen) then
					blur:Destroy()
					self._blur = nil
				end
			end)
		end
	end

	function App:SetMenuKey(key)
		local name = typeof(key) == "EnumItem" and key.Name or key
		self.ctx.Keybinds:Assign(self._menuBind, name)
	end

	function App:GetMenuBind()
		return self._menuBind
	end

	function App:SetNotifications(opts)
		if opts.Enabled ~= nil then
			self.Notifications.Enabled = opts.Enabled
		end
		if opts.Duration then
			self.ctx.NotifyDuration = opts.Duration
		end
		if opts.Position then
			self.Notifications:SetPosition(opts.Position)
		end
		if opts.Sound ~= nil then
			if opts.Sound then
				self.ctx.NotifySound = function()
					local sound = Instance.new("Sound")
					sound.SoundId = "rbxasset://sounds/electronicpingshort.wav"
					sound.Volume = 0.35
					SoundService:PlayLocalSound(sound)
					task.delay(2, function()
						sound:Destroy()
					end)
				end
			else
				self.ctx.NotifySound = nil
			end
		end
	end

	function App:SetTooltips(enabled)
		self.ctx.Tooltip.Enabled = enabled
		if not enabled then
			self.ctx.Tooltip:Hide()
		end
	end

	function App:ResetPosition()
		self.Window:Center()
	end

	function App:Destroy()
		for _, connection in ipairs(self._connections) do
			connection:Disconnect()
		end
		self.ctx.Keybinds:Destroy()
		self.ctx.Popups:Destroy()
		if self._blur then
			self._blur:Destroy()
		end
		self.Gui:Destroy()
	end

	return Nocturne
end

__node("Nocturne.Builtins.ConfigsTab")
__modules["Nocturne.Builtins.ConfigsTab"] = function(script, require)
	--[[
		Built-in Configs tab
		Save, load, rename and delete named configs, plus JSON export / import.
		Uses DataStore persistence when Server/ConfigPersistence is installed,
		otherwise configs last for the session.
	]]

	return function(app)
		local configs = app.Configs
		local page = app:Page({ Name = "Configs", Icon = "configs" })

		local manage = page:Section({ Title = "Configs" })
		local nameInput = manage:Input({
			Text = "Config name",
			Placeholder = "e.g. ranked, casual, streaming",
			MaxLength = 32,
		})
		local list = manage:ListBox({ Height = 150, Empty = "No configs saved yet", Icon = "configs" })

		local details -- filled in below
		local function refresh(keep)
			list:SetItems(configs:List(), keep)
			details.update(list:GetSelected())
		end

		local function report(ok, message)
			app:Notify({ Title = ok and "Configs" or "Couldn't complete that", Text = message, Type = ok and "success" or "warning" })
		end

		manage:Buttons({
			{
				Text = "Save",
				Icon = "save",
				Style = "Primary",
				Callback = function()
					local name = nameInput:Get()
					if name == "" and list:GetSelected() then
						name = list:GetSelected()
					end
					local ok, message = configs:Save(name)
					report(ok, message)
					if ok then
						refresh(true)
					end
				end,
			},
			{
				Text = "Load",
				Icon = "load",
				Callback = function()
					report(configs:Load(list:GetSelected()))
				end,
			},
		})
		manage:Buttons({
			{
				Text = "Rename",
				Icon = "pencil",
				Callback = function()
					local ok, message = configs:Rename(list:GetSelected(), nameInput:Get())
					report(ok, message)
					if ok then
						nameInput:Set("", true)
						refresh(false)
					end
				end,
			},
			{
				Text = "Delete",
				Icon = "trash",
				Style = "Danger",
				Callback = function()
					local ok, message = configs:Delete(list:GetSelected())
					report(ok, message)
					if ok then
						refresh(false)
					end
				end,
			},
		})

		local selected = page:Section({ Title = "Selected", Side = "Right" })
		local nameInfo = selected:Info({ Text = "Name", Value = "-" })
		local countInfo = selected:Info({ Text = "Settings", Value = "-" })
		local savedInfo = selected:Info({ Text = "Saved", Value = "-" })
		local sizeInfo = selected:Info({ Text = "Size", Value = "-" })
		selected:Info({ Text = "Storage", Value = configs.Persistent and "Cloud (DataStore)" or "This session", Accent = true })
		details = {
			update = function(name)
				local info = name and configs:Info(name)
				nameInfo:Set(info and info.Name or "-")
				countInfo:Set(info and info.Flags or "-")
				savedInfo:Set(info and os.date("%b %d, %H:%M", info.Saved) or "-")
				sizeInfo:Set(info and ("%.1f KB"):format(info.Size / 1024) or "-")
			end,
		}
		list.Selected:Connect(function(name)
			details.update(name)
		end)

		local transfer = page:Section({ Title = "Share", Side = "Right" })
		local json = transfer:Input({
			Text = "Config JSON",
			Placeholder = "Export, then select the text to copy",
			Save = false,
		})
		transfer:Buttons({
			{
				Text = "Export",
				Icon = "copy",
				Callback = function()
					json:Set(configs:Export(), true)
					json.Box:CaptureFocus()
					json.Box.SelectionStart = 1
					json.Box.CursorPosition = #json.Box.Text + 1
					app:Notify({ Title = "Exported", Text = "Current settings are in the field, selected for copying.", Type = "success" })
				end,
			},
			{
				Text = "Import",
				Icon = "load",
				Callback = function()
					report(configs:Import(json:Get()))
				end,
			},
		})
		transfer:Label("Export copies your current settings, not the selected config. Paste JSON and press Import to apply it.", "Muted")

		configs.Changed:Connect(function()
			refresh(true)
		end)
		refresh(false)
	end
end

__node("Nocturne.Builtins.SettingsTab")
__modules["Nocturne.Builtins.SettingsTab"] = function(script, require)
	--[[
		Built-in Settings tab
		Themes, accent colour, transparency, gloss, UI scale, motion, menu key,
		notifications and overlays, all applied live through the app API.
		Disable with CreateWindow({ SettingsTab = false }).
	]]

	local Presets = require(script.Parent.Parent.Themes.Presets)

	return function(app)
		local page = app:Page({ Name = "Settings", Icon = "settings" })

		local theme = page:Section({ Title = "Theme" })
		local accent
		theme:Dropdown({
			Text = "Preset",
			Options = Presets.Order,
			Default = app.Theme.Name,
			Flag = "UI.Theme",
			Callback = function(name)
				app:SetTheme(name)
				-- Without a custom accent, the swatch follows the preset's accent.
				if not app.Theme.Values.Accent then
					accent:Set(app.Theme.Tokens.Accent, true)
				end
			end,
		})
		accent = theme:ColorPicker({
			Text = "Accent color",
			Default = app.Theme.Tokens.Accent,
			Flag = "UI.Accent",
			Presets = Presets.Accents,
			Callback = function(color)
				app:SetAccent(color)
			end,
		})
		theme:Slider({
			Text = "Window transparency",
			Min = 0,
			Max = 40,
			Default = 4,
			Suffix = "%",
			Flag = "UI.Transparency",
			Callback = function(v)
				app:SetTransparency(v / 100)
			end,
		})
		theme:Switch({
			Text = "Glossy effects",
			Default = true,
			Flag = "UI.Gloss",
			Callback = function(v)
				app:SetGloss(v)
			end,
		})
		theme:Switch({
			Text = "Blur world behind window",
			Flag = "UI.Blur",
			Callback = function(v)
				app:SetBlur(v)
			end,
		})
		theme:Button({
			Text = "Use theme accent",
			Callback = function()
				app:SetAccent(nil)
				accent:Set(app.Theme.Tokens.Accent, true)
			end,
		})

		local interface = page:Section({ Title = "Interface" })
		interface:Slider({
			Text = "UI scale",
			Min = 70,
			Max = 130,
			Step = 5,
			Default = 100,
			Suffix = "%",
			Flag = "UI.Scale",
			Callback = function(v)
				app:SetScale(v / 100)
			end,
		})
		interface:Keybind({
			Text = "Menu key",
			Bind = app:GetMenuBind(),
			Flag = "UI.MenuKey",
			Tooltip = "Toggles the window. Backspace can't clear this one.",
		})
		interface:Switch({
			Text = "Tooltips",
			Default = true,
			Flag = "UI.Tooltips",
			Callback = function(v)
				app:SetTooltips(v)
			end,
		})
		interface:Switch({
			Text = "Collapse on reselect",
			Default = true,
			Flag = "UI.CollapseOnReselect",
			Tooltip = "Clicking the active dock icon again closes the window.",
			Callback = function(v)
				app.CollapseOnReselect = v
			end,
		})
		interface:Button({
			Text = "Re-centre window",
			Callback = function()
				app:ResetPosition()
			end,
		})

		local motion = page:Section({ Title = "Animations", Side = "Right" })
		motion:Switch({
			Text = "Reduced motion",
			Flag = "UI.ReducedMotion",
