__node("Nocturne.Components.Tooltip")
__modules["Nocturne.Components.Tooltip"] = function(script, require)
	--[[
		Tooltip
		One shared tooltip in the overlay layer. Elements opt in with
		Tooltip:Attach(guiObject, text). It appears after a short hover delay,
		is placed beside the element and clamped to the screen.
	]]

	local Util = require(script.Parent.Parent.Core.Util)
	local Motion = require(script.Parent.Parent.Animations.Motion)

	local Tooltip = {}
	Tooltip.__index = Tooltip

	local DELAY = 0.35
	local MAX_WIDTH = 220

	function Tooltip.new(ctx)
		local self = setmetatable({ ctx = ctx, _token = 0, Enabled = true }, Tooltip)

		local frame = Util.frame({
			Name = "Tooltip",
			AutomaticSize = Enum.AutomaticSize.XY,
			BackgroundTransparency = 1,
			Visible = false,
			ZIndex = 200,
			Parent = ctx.Overlay,
		})
		Util.corner(frame, 6)
		Util.padding(frame, 6, 9)
		local stroke = Util.stroke(frame, { Transparency = 1 })
		local label = Util.text({
			AutomaticSize = Enum.AutomaticSize.XY,
			TextSize = 11,
			TextWrapped = true,
			TextTransparency = 1,
			ZIndex = 201,
			Parent = frame,
		})
		Util.new("UISizeConstraint", { MaxSize = Vector2.new(MAX_WIDTH, math.huge), Parent = label })
		self._scale = Util.new("UIScale", { Parent = frame })

		ctx.Theme:Bind(frame, { BackgroundColor3 = "Elevated" })
		ctx.Theme:Bind(stroke, { Color = "BorderStrong" })
		ctx.Theme:Bind(label, { TextColor3 = "TextDim" })

		self.Frame, self.Label, self.Stroke = frame, label, stroke
		return self
	end

	function Tooltip:Show(target, text)
		if not self.Enabled then
			return
		end
		self._token += 1
		local token = self._token
		task.delay(DELAY, function()
			if token ~= self._token or not target.Parent or not target.Visible then
				return
			end
			local frame = self.Frame
			self._scale.Scale = self.ctx:GetScale()
			self.Label.Text = text
			frame.Visible = true

			-- Measure after layout, then place to the right of the target,
			-- falling back below / left when the screen edge is near.
			task.defer(function()
				if token ~= self._token then
					return
				end
				local viewport = self.ctx.Gui.AbsoluteSize
				local size = frame.AbsoluteSize
				local position = target.AbsolutePosition
				local targetSize = target.AbsoluteSize
				local x = position.X + targetSize.X + 8
				local y = position.Y + targetSize.Y / 2 - size.Y / 2
				if x + size.X > viewport.X - 8 then
					x = position.X + targetSize.X - size.X
					y = position.Y + targetSize.Y + 6
				end
				x = math.clamp(x, 8, math.max(8, viewport.X - size.X - 8))
				y = math.clamp(y, 8, math.max(8, viewport.Y - size.Y - 8))
				frame.Position = UDim2.fromOffset(x, y + 3)
				Motion.tween(frame, "Fast", { Position = UDim2.fromOffset(x, y), BackgroundTransparency = 0.02 })
				Motion.tween(self.Label, "Fast", { TextTransparency = 0 })
				Motion.tween(self.Stroke, "Fast", { Transparency = 0.2 })
			end)
		end)
	end

	function Tooltip:Hide()
		self._token += 1
		local token = self._token
		Motion.tween(self.Frame, "Fast", { BackgroundTransparency = 1 })
		Motion.tween(self.Stroke, "Fast", { Transparency = 1 })
		Motion.tween(self.Label, "Fast", { TextTransparency = 1 }, function()
			if token == self._token then
				self.Frame.Visible = false
			end
		end)
	end

	function Tooltip:Attach(target, text)
		local enter = target.MouseEnter:Connect(function()
			self:Show(target, text)
		end)
		local leave = target.MouseLeave:Connect(function()
			self:Hide()
		end)
		target.Destroying:Once(function()
			enter:Disconnect()
			leave:Disconnect()
		end)
	end

	return Tooltip
end

__node("Nocturne.Config.ConfigManager")
__modules["Nocturne.Config.ConfigManager"] = function(script, require)
	--[[
		ConfigManager
		Saves / loads the values of every flagged control.

		Storage
		- If ReplicatedStorage has a RemoteFunction named "NocturneConfigs"
		  (created by Server/ConfigPersistence.server.luau) configs persist per
		  player through DataStoreService.
		- Otherwise configs live in memory for the session; export / import
		  still lets players move them around as JSON text.

		All methods yield when a remote is used; call them from callbacks
		(already spawned) or task.spawn.
	]]

	local HttpService = game:GetService("HttpService")
	local ReplicatedStorage = game:GetService("ReplicatedStorage")

	local Signal = require(script.Parent.Parent.Core.Signal)

	local ConfigManager = {}
	ConfigManager.__index = ConfigManager

	local REMOTE_NAME = "NocturneConfigs"
	local MAX_NAME = 32
	local FORMAT = 1

	function ConfigManager.new(state)
		local self = setmetatable({
			State = state,
			_store = {}, -- name -> { Data = table, Saved = unix time }
			Changed = Signal.new(),
			Persistent = false,
		}, ConfigManager)

		local remote = ReplicatedStorage:FindFirstChild(REMOTE_NAME)
		if remote and remote:IsA("RemoteFunction") then
			self._remote = remote
			self.Persistent = true
			task.spawn(function()
				local ok, result = pcall(remote.InvokeServer, remote, "fetch")
				if ok and type(result) == "table" then
					for name, json in pairs(result) do
						local decoded = self:_decode(json)
						if decoded then
							self._store[name] = decoded
						end
					end
					self.Changed:Fire()
				end
			end)
		end
		return self
	end

	function ConfigManager.sanitize(name)
		if type(name) ~= "string" then
			return nil
		end
		name = string.gsub(name, "[^%w%s%-_%.]", "")
		name = string.match(name, "^%s*(.-)%s*$")
		if name == "" then
			return nil
		end
		return string.sub(name, 1, MAX_NAME)
	end

	function ConfigManager:_decode(json)
		local ok, decoded = pcall(HttpService.JSONDecode, HttpService, json)
		if ok and type(decoded) == "table" and type(decoded.Flags) == "table" then
			return { Data = decoded.Flags, Saved = tonumber(decoded.Saved) or 0 }
		end
		return nil
	end

	function ConfigManager:_encode(entry)
		return HttpService:JSONEncode({ Format = FORMAT, Saved = entry.Saved, Flags = entry.Data })
	end

	function ConfigManager:_push(action, name, json)
		if not self._remote then
			return true
		end
		local ok, result = pcall(self._remote.InvokeServer, self._remote, action, name, json)
		return ok and result == true, ok and result or "Storage unavailable"
	end

	function ConfigManager:List()
		local names = {}
		for name in pairs(self._store) do
			table.insert(names, name)
		end
		table.sort(names, function(a, b)
			return string.lower(a) < string.lower(b)
		end)
		return names
	end

	function ConfigManager:Info(name)
		local entry = self._store[name]
		if not entry then
			return nil
		end
		local count = 0
		for _ in pairs(entry.Data) do
			count += 1
		end
		return { Name = name, Flags = count, Saved = entry.Saved, Size = #self:_encode(entry) }
	end

	-- Returns ok, message
	function ConfigManager:Save(name)
		name = ConfigManager.sanitize(name)
		if not name then
			return false, "Enter a config name first."
		end
		local entry = { Data = self.State:Serialize(), Saved = os.time() }
		local ok, err = self:_push("save", name, self:_encode(entry))
		if not ok then
			return false, tostring(err)
		end
		self._store[name] = entry
		self.Changed:Fire()
		return true, ("Saved '%s'."):format(name)
	end

	function ConfigManager:Load(name)
		local entry = self._store[name]
		if not entry then
			return false, "Select a config to load."
		end
		local applied = self.State:Apply(entry.Data)
		return true, ("Loaded '%s' (%d settings)."):format(name, applied)
	end

	function ConfigManager:Delete(name)
		if not self._store[name] then
			return false, "Select a config to delete."
		end
		local ok, err = self:_push("delete", name)
		if not ok then
			return false, tostring(err)
		end
		self._store[name] = nil
		self.Changed:Fire()
		return true, ("Deleted '%s'."):format(name)
	end

	function ConfigManager:Rename(old, new)
		new = ConfigManager.sanitize(new)
		if not self._store[old] then
			return false, "Select a config to rename."
		elseif not new then
			return false, "Enter the new name in the name field."
		elseif self._store[new] then
			return false, ("'%s' already exists."):format(new)
		end
		local entry = self._store[old]
		local ok, err = self:_push("save", new, self:_encode(entry))
		if not ok then
			return false, tostring(err)
		end
		self:_push("delete", old)
		self._store[new] = entry
		self._store[old] = nil
		self.Changed:Fire()
		return true, ("Renamed to '%s'."):format(new)
	end

	-- Current settings (not a stored config) as portable JSON.
	function ConfigManager:Export()
		return self:_encode({ Data = self.State:Serialize(), Saved = os.time() })
	end

	function ConfigManager:Import(json)
		if type(json) ~= "string" or json == "" then
			return false, "Paste exported JSON into the field first."
		end
		local entry = self:_decode(json)
		if not entry then
			return false, "That text isn't a valid Nocturne config."
		end
		local applied = self.State:Apply(entry.Data)
		return true, ("Imported %d settings."):format(applied)
	end

	return ConfigManager
end

__node("Nocturne.Core.Keybinds")
__modules["Nocturne.Core.Keybinds"] = function(script, require)
	--[[
		Keybinds
		Central registry for every bindable key, so bindings can be listened for
		with one input connection and conflicting assignments can be refused.

		bind = {
			Name    = "Ability 1",
			Key     = "Q" | "MB2" | nil,     -- stored as a string id
			OnPress = fn(), OnRelease = fn()?,
			Locked  = boolean?               -- e.g. the menu key cannot be cleared
		}

		While a pill is capturing, every other binding is suspended.
		Escape cancels, Backspace / Delete clears, a left click elsewhere cancels.
	]]

	local UserInputService = game:GetService("UserInputService")

	local Signal = require(script.Parent.Signal)

	local Keybinds = {}
	Keybinds.__index = Keybinds

	local SHORT = {
		LeftShift = "LShift", RightShift = "RShift",
		LeftControl = "LCtrl", RightControl = "RCtrl",
		LeftAlt = "LAlt", RightAlt = "RAlt",
		Return = "Enter", Backquote = "`", Minus = "-", Equals = "=",
		LeftBracket = "[", RightBracket = "]", Semicolon = ";", Quote = "'",
		Comma = ",", Period = ".", Slash = "/", BackSlash = "\\",
		Zero = "0", One = "1", Two = "2", Three = "3", Four = "4",
		Five = "5", Six = "6", Seven = "7", Eight = "8", Nine = "9",
		PageUp = "PgUp", PageDown = "PgDn", Insert = "Ins", CapsLock = "Caps",
		MB2 = "M2", MB3 = "M3",
	}

	-- Keys that would fight Roblox core controls or break text input.
	local RESERVED = {
		Escape = true, Tab = true, Slash = true,
		F9 = true, F11 = true, Unknown = true,
	}

	function Keybinds.display(key)
		if not key then
			return "none"
		end
		return SHORT[key] or key
	end

	local function keyFromInput(input)
		if input.UserInputType == Enum.UserInputType.Keyboard then
			return input.KeyCode.Name
		elseif input.UserInputType == Enum.UserInputType.MouseButton2 then
			return "MB2"
		elseif input.UserInputType == Enum.UserInputType.MouseButton3 then
			return "MB3"
		end
		return nil
	end

	function Keybinds.new()
		local self = setmetatable({
			_binds = {},
			_capture = nil,
			Changed = Signal.new(),
			Pressed = Signal.new(),
			Enabled = true,
		}, Keybinds)

		self._began = UserInputService.InputBegan:Connect(function(input, processed)
			self:_onBegan(input, processed)
		end)
		self._ended = UserInputService.InputEnded:Connect(function(input)
			local key = keyFromInput(input)
			if not key or self._capture then
				return
			end
			for _, bind in ipairs(self._binds) do
				if bind.Key == key and bind.OnRelease then
					task.spawn(bind.OnRelease)
				end
			end
		end)
		return self
	end

	function Keybinds:Register(bind)
		table.insert(self._binds, bind)
		self.Changed:Fire()
		return bind
	end

	function Keybinds:Unregister(bind)
		local index = table.find(self._binds, bind)
		if index then
			table.remove(self._binds, index)
			self.Changed:Fire()
		end
	end

	function Keybinds:All()
		return self._binds
	end

	function Keybinds:FindConflict(key, except)
		if not key then
			return nil
		end
		for _, bind in ipairs(self._binds) do
			if bind ~= except and bind.Key == key then
				return bind
			end
		end
		return nil
	end

	function Keybinds:IsCapturing()
		return self._capture ~= nil
	end

	--[[
		Starts listening for a new key for `bind`.
		onDone(result, detail) where result is
			"set"      detail = key
			"cleared"
			"cancel"
			"conflict" detail = other bind
			"reserved" detail = key
	]]
	function Keybinds:Capture(bind, onDone)
		if self._capture then
			self:_finish("cancel")
		end
		self._capture = { bind = bind, onDone = onDone }
	end

	function Keybinds:CancelCapture()
		if self._capture then
			self:_finish("cancel")
		end
	end

	function Keybinds:_finish(result, detail)
		local capture = self._capture
		self._capture = nil
		if capture then
			task.spawn(capture.onDone, result, detail)
		end
	end

	function Keybinds:Assign(bind, key)
		bind.Key = key
		self.Changed:Fire()
	end

	function Keybinds:_onBegan(input, processed)
		if self._capture then
			if input.UserInputType == Enum.UserInputType.MouseButton1 or input.UserInputType == Enum.UserInputType.Touch then
				self:_finish("cancel")
				return
			end
			local key = keyFromInput(input)
			if not key then
				return
			end
			local bind = self._capture.bind
			if key == "Escape" then
				self:_finish("cancel")
			elseif key == "Backspace" or key == "Delete" then
				if bind.Locked then
					self:_finish("cancel")
				else
					self:Assign(bind, nil)
					self:_finish("cleared")
				end
			elseif RESERVED[key] then
				self:_finish("reserved", key)
			else
				local other = self:FindConflict(key, bind)
				if other then
					self:_finish("conflict", other)
				else
					self:Assign(bind, key)
					self:_finish("set", key)
				end
			end
			return
		end

		if not self.Enabled then
			return
		end
		-- Ignore keys typed into text boxes / chat.
		if processed and input.UserInputType == Enum.UserInputType.Keyboard then
			return
		end
		if UserInputService:GetFocusedTextBox() then
			return
		end
		local key = keyFromInput(input)
		if not key then
			return
		end
		for _, bind in ipairs(table.clone(self._binds)) do
			if bind.Key == key and bind.OnPress then
				task.spawn(bind.OnPress)
				self.Pressed:Fire(bind)
			end
		end
	end

	function Keybinds:Destroy()
		self._began:Disconnect()
		self._ended:Disconnect()
		self.Changed:Destroy()
		self.Pressed:Destroy()
	end

	return Keybinds
end

__node("Nocturne.Core.Maid")
__modules["Nocturne.Core.Maid"] = function(script, require)
	--[[
		Maid
		Collects connections, instances and cleanup functions so a component
		can release everything it created in one call.
	]]

	local Maid = {}
	Maid.__index = Maid

	function Maid.new()
		return setmetatable({ _tasks = {} }, Maid)
	end

	function Maid:Give(item)
		table.insert(self._tasks, item)
		return item
	end

	local function cleanup(item)
		local kind = typeof(item)
		if kind == "RBXScriptConnection" then
			item:Disconnect()
		elseif kind == "function" then
			item()
		elseif kind == "Instance" then
			item:Destroy()
		elseif kind == "table" then
			if item.Disconnect then
				item.Disconnect(item)
			elseif item.Destroy then
				item:Destroy()
			end
		end
	end

	function Maid:Clean()
		local tasks = self._tasks
		self._tasks = {}
		for index = #tasks, 1, -1 do
			cleanup(tasks[index])
		end
	end

	-- Cleans automatically when the given instance is destroyed.
	function Maid:LinkTo(instance)
		self:Give(instance.Destroying:Connect(function()
			self:Clean()
		end))
		return self
	end

	Maid.Destroy = Maid.Clean

	return Maid
end

__node("Nocturne.Core.Popups")
__modules["Nocturne.Core.Popups"] = function(script, require)
	--[[
		Popups
		Ensures only one floating popup (dropdown list, colour picker) is open
		at a time and closes it when the user presses anywhere outside of it.

		popup = { Close = fn(), Contains = fn(point: Vector2) -> boolean }
	]]

	local UserInputService = game:GetService("UserInputService")

	local Util = require(script.Parent.Util)

	local Popups = {}
	Popups.__index = Popups

	function Popups.new()
		local self = setmetatable({ Current = nil }, Popups)
		self._connection = UserInputService.InputBegan:Connect(function(input)
			local current = self.Current
			if not current or not Util.isPress(input) then
				return
			end
			if not current.Contains(Util.pointer(input)) then
				self:Close(current)
			end
		end)
		return self
	end

	function Popups:Open(popup)
		if self.Current and self.Current ~= popup then
			self:Close(self.Current)
		end
		self.Current = popup
	end

	function Popups:Close(popup)
		popup = popup or self.Current
		if not popup then
			return
		end
		if self.Current == popup then
			self.Current = nil
		end
		popup.Close()
	end

	function Popups:Released(popup)
		if self.Current == popup then
			self.Current = nil
		end
	end

	function Popups:CloseAll()
		self:Close(self.Current)
	end

	function Popups:Destroy()
		self._connection:Disconnect()
	end

	return Popups
end

__node("Nocturne.Core.Signal")
__modules["Nocturne.Core.Signal"] = function(script, require)
	--[[
		Signal
		Minimal event object. Handlers run through task.spawn so one failing
		listener never breaks the caller or the other listeners.
	]]

	local Signal = {}
	Signal.__index = Signal

	function Signal.new()
		return setmetatable({ _entries = {} }, Signal)
	end

	function Signal:Connect(fn)
		local entries = self._entries
		local entry = { fn = fn, connected = true }
		table.insert(entries, entry)

		local connection = { Connected = true }
		function connection.Disconnect()
			if not entry.connected then
				return
			end
			entry.connected = false
			connection.Connected = false
			local index = table.find(entries, entry)
			if index then
				table.remove(entries, index)
			end
		end
		return connection
	end

	function Signal:Once(fn)
		local connection
		connection = self:Connect(function(...)
			connection.Disconnect()
			fn(...)
		end)
		return connection
	end

	function Signal:Fire(...)
		for _, entry in ipairs(table.clone(self._entries)) do
			if entry.connected then
				task.spawn(entry.fn, ...)
			end
		end
	end

	function Signal:Destroy()
		for _, entry in ipairs(self._entries) do
			entry.connected = false
		end
		table.clear(self._entries)
	end

	return Signal
end

__node("Nocturne.Core.State")
__modules["Nocturne.Core.State"] = function(script, require)
	--[[
		State
		Registry of flagged controls. Every control created with a `Flag`
		registers a getter/setter here, which is what configs save and load.
	]]

	local Signal = require(script.Parent.Signal)

	local State = {}
	State.__index = State

	function State.new()
		return setmetatable({
			_flags = {},
			Changed = Signal.new(),
		}, State)
	end

	-- handle = { Get = fn() -> value, Set = fn(value), Save = boolean? }
	function State:Register(flag, handle)
		if self._flags[flag] then
			warn(("[Nocturne] Flag '%s' registered twice; the newest control wins."):format(flag))
		end
		self._flags[flag] = handle
	end

	function State:Unregister(flag, handle)
		if self._flags[flag] == handle then
			self._flags[flag] = nil
		end
	end

	function State:Get(flag)
		local handle = self._flags[flag]
		return handle and handle.Get()
	end

	function State:Set(flag, value)
		local handle = self._flags[flag]
		if handle then
			handle.Set(value)
		end
	end

	function State:Notify(flag, value)
		self.Changed:Fire(flag, value)
	end

	local function encode(value)
		if typeof(value) == "Color3" then
			return { Color = value:ToHex() }
		end
		return value
	end

	local function decode(value)
		if type(value) == "table" and type(value.Color) == "string" then
			local ok, color = pcall(Color3.fromHex, value.Color)
			return ok and color or nil
		end
		return value
	end

	function State:Serialize()
		local out = {}
		for flag, handle in pairs(self._flags) do
			if handle.Save ~= false then
				out[flag] = encode(handle.Get())
			end
		end
		return out
	end

	-- Applies saved values. Unknown flags are ignored; returns the count applied.
	function State:Apply(data)
		local applied = 0
		if type(data) ~= "table" then
			return applied
		end
		for flag, raw in pairs(data) do
			local handle = self._flags[flag]
			local value = decode(raw)
			if handle and handle.Save ~= false and value ~= nil then
				local ok, err = pcall(handle.Set, value)
				if ok then
					applied += 1
				else
					warn(("[Nocturne] Could not apply flag '%s': %s"):format(flag, tostring(err)))
				end
			end
		end
		return applied
	end

	return State
end

__node("Nocturne.Core.Util")
__modules["Nocturne.Core.Util"] = function(script, require)
	--[[
		Util
		Instance construction helpers plus the shared "glass surface" used by the
		toolbar, window, popups and overlays.
	]]

	local GuiService = game:GetService("GuiService")
	local UserInputService = game:GetService("UserInputService")

	local Motion = require(script.Parent.Parent.Animations.Motion)

	local Util = {}

	local FAMILY = "rbxasset://fonts/families/BuilderSans.json"

	Util.Fonts = {
		Regular = Font.new(FAMILY, Enum.FontWeight.Regular),
		Medium = Font.new(FAMILY, Enum.FontWeight.Medium),
		SemiBold = Font.new(FAMILY, Enum.FontWeight.SemiBold),
		Bold = Font.new(FAMILY, Enum.FontWeight.Bold),
	}

	function Util.new(className, props, children)
		local instance = Instance.new(className)
		local parent
		for key, value in pairs(props or {}) do
			if key == "Parent" then
				parent = value
			else
				instance[key] = value
			end
		end
		for _, child in ipairs(children or {}) do
			child.Parent = instance
		end
		if parent then
			instance.Parent = parent
		end
		return instance
	end

	function Util.frame(props, children)
		local defaults = {
			BackgroundTransparency = 1,
			BorderSizePixel = 0,
		}
		for key, value in pairs(props or {}) do
			defaults[key] = value
		end
		return Util.new("Frame", defaults, children)
	end

	function Util.text(props)
		local defaults = {
			BackgroundTransparency = 1,
			BorderSizePixel = 0,
			FontFace = Util.Fonts.Medium,
			TextSize = 12,
			TextXAlignment = Enum.TextXAlignment.Left,
			TextYAlignment = Enum.TextYAlignment.Center,
			Text = "",
		}
		for key, value in pairs(props or {}) do
			defaults[key] = value
		end
		return Util.new("TextLabel", defaults)
	end

	function Util.button(props)
		local defaults = {
			BackgroundTransparency = 1,
			BorderSizePixel = 0,
			AutoButtonColor = false,
			Text = "",
			Selectable = true,
		}
		for key, value in pairs(props or {}) do
			defaults[key] = value
		end
		return Util.new("TextButton", defaults)
	end

	function Util.corner(parent, radius)
		return Util.new("UICorner", {
			CornerRadius = typeof(radius) == "UDim" and radius or UDim.new(0, radius or 6),
			Parent = parent,
		})
	end

	function Util.stroke(parent, props)
		local defaults = {
			ApplyStrokeMode = Enum.ApplyStrokeMode.Border,
			Thickness = 1,
			Parent = parent,
		}
		for key, value in pairs(props or {}) do
			defaults[key] = value
		end
		return Util.new("UIStroke", defaults)
	end

	-- CSS-style padding: (all) | (vertical, horizontal) | (top, right, bottom, left)
	function Util.padding(parent, top, right, bottom, left)
		right = right or top
		bottom = bottom or top
		left = left or right
		return Util.new("UIPadding", {
			PaddingTop = UDim.new(0, top),
			PaddingRight = UDim.new(0, right),
			PaddingBottom = UDim.new(0, bottom),
			PaddingLeft = UDim.new(0, left),
			Parent = parent,
		})
	end

	function Util.list(parent, props)
		local defaults = {
			FillDirection = Enum.FillDirection.Vertical,
			SortOrder = Enum.SortOrder.LayoutOrder,
			Padding = UDim.new(0, 0),
			Parent = parent,
		}
		for key, value in pairs(props or {}) do
			if key == "Padding" and type(value) == "number" then
				value = UDim.new(0, value)
			end
			defaults[key] = value
		end
		return Util.new("UIListLayout", defaults)
	end

	-- Vertical top-lit gradient that gives fills their soft glossy depth.
	function Util.gloss(parent, strength)
		strength = strength or 0.1
		local low = 1 - strength
		return Util.new("UIGradient", {
			Rotation = 90,
			Color = ColorSequence.new({
				ColorSequenceKeypoint.new(0, Color3.new(1, 1, 1)),
				ColorSequenceKeypoint.new(0.55, Color3.new(1 - strength * 0.45, 1 - strength * 0.45, 1 - strength * 0.45)),
				ColorSequenceKeypoint.new(1, Color3.new(low, low, low)),
			}),
			Parent = parent,
		})
	end

	-- 1px highlight just inside the top edge, faded towards the corners.
	function Util.sheen(parent, inset, transparency)
		inset = inset or 8
		local line = Util.frame({
			Name = "Sheen",
			BackgroundTransparency = transparency or 0.9,
			BackgroundColor3 = Color3.new(1, 1, 1),
			Position = UDim2.fromOffset(inset, 1),
			Size = UDim2.new(1, -inset * 2, 0, 1),
			ZIndex = 9,
			Parent = parent,
		})
		Util.new("UIGradient", {
			Transparency = NumberSequence.new({
				NumberSequenceKeypoint.new(0, 1),
				NumberSequenceKeypoint.new(0.2, 0.2),
				NumberSequenceKeypoint.new(0.8, 0.2),
				NumberSequenceKeypoint.new(1, 1),
			}),
			Parent = line,
		})
		return line
	end

	-- Stroke that is brighter on the top edge than on the bottom edge.
	function Util.glassStroke(ctx, parent, token, transparency)
		local stroke = Util.stroke(parent, { Transparency = transparency or 0 })
		ctx.Theme:Bind(stroke, { Color = token or "BorderStrong" })
		Util.new("UIGradient", {
			Rotation = 90,
			Color = ColorSequence.new(Color3.new(1, 1, 1), Color3.new(0.62, 0.62, 0.62)),
			Parent = stroke,
		})
		return stroke
	end

	-- Converts an InputObject position to ScreenGui space (IgnoreGuiInset = true).
	function Util.pointer(input)
		local inset = GuiService:GetGuiInset()
		if input then
			return Vector2.new(input.Position.X, input.Position.Y) + inset
		end
		return UserInputService:GetMouseLocation()
	end

	function Util.contains(guiObject, point, margin)
		if not guiObject or not guiObject.Parent then
			return false
		end
		margin = margin or 0
		local position = guiObject.AbsolutePosition
		local size = guiObject.AbsoluteSize
		return point.X >= position.X - margin
			and point.X <= position.X + size.X + margin
			and point.Y >= position.Y - margin
			and point.Y <= position.Y + size.Y + margin
	end

	function Util.isPress(input)
		return input.UserInputType == Enum.UserInputType.MouseButton1 or input.UserInputType == Enum.UserInputType.Touch
	end

	function Util.isMove(input)
		return input.UserInputType == Enum.UserInputType.MouseMovement or input.UserInputType == Enum.UserInputType.Touch
	end

	function Util.decimals(step)
		local text = string.format("%.6g", step)
		local fraction = string.match(text, "%.(%d+)$")
		return fraction and #fraction or 0
	end

	function Util.round(value, step)
		if step <= 0 then
			return value
		end
		return math.floor(value / step + 0.5) * step
	end

	--[[
		Glass surface: a holder Frame containing layered soft shadows and a
		rounded CanvasGroup body. The CanvasGroup clips children to its rounded
		corners and lets the whole surface fade through GroupTransparency.

		Returns { Holder, Body, Fill, Shadows, SetAlpha(alpha, preset) }
	]]
	function Util.surface(ctx, opts)
		opts = opts or {}
		local radius = opts.Radius or 10
		local layers = opts.ShadowLayers or 5
		local spread = opts.ShadowSpread or 3
		local shadowAlpha = opts.ShadowTransparency or 0.92
		local fillToken = opts.Fill or "Backdrop"

		local holder = Util.frame({
			Name = opts.Name or "Surface",
			Size = opts.Size or UDim2.fromOffset(100, 100),
			Position = opts.Position or UDim2.new(),
			AnchorPoint = opts.AnchorPoint or Vector2.zero,
			ZIndex = opts.ZIndex or 1,
			Parent = opts.Parent,
		})

		local shadows = {}
		for index = layers, 1, -1 do
			local grow = index * spread
			local shadow = Util.frame({
				Name = "Shadow" .. index,
				AnchorPoint = Vector2.new(0.5, 0.5),
				Position = UDim2.new(0.5, 0, 0.5, opts.ShadowOffset or 4),
				Size = UDim2.new(1, grow * 2, 1, grow * 2),
				BackgroundTransparency = shadowAlpha,
				ZIndex = 0,
				Parent = holder,
			})
			Util.corner(shadow, radius + grow)
			ctx.Theme:Bind(shadow, { BackgroundColor3 = "Shadow" })
			table.insert(shadows, shadow)
		end

		local body = Util.new("CanvasGroup", {
			Name = "Body",
			AnchorPoint = Vector2.new(0.5, 0.5),
			Position = UDim2.fromScale(0.5, 0.5),
			Size = UDim2.fromScale(1, 1),
			BackgroundTransparency = 1,
			BorderSizePixel = 0,
			ZIndex = 1,
			Parent = holder,
		})
		Util.corner(body, radius)

		local fill = Util.frame({
			Name = "Fill",
			Size = UDim2.fromScale(1, 1),
			BackgroundTransparency = 0,
			ZIndex = 0,
			Parent = body,
		})
		Util.corner(fill, radius)
		local fillMap = { BackgroundColor3 = fillToken }
		if type(opts.FillTransparency) == "number" then
			fill.BackgroundTransparency = opts.FillTransparency
		else
			fillMap.BackgroundTransparency = opts.FillTransparency or function(tokens)
				return tokens.Transparency
			end
		end
		ctx.Theme:Bind(fill, fillMap)
		local gloss = Util.gloss(fill, opts.GlossStrength or 0.12)
		ctx:RegisterGloss(gloss)

		-- Inner edge: a frame inset by 1px whose outside stroke lands exactly on
		-- the body's outermost pixel, so it survives CanvasGroup clipping.
		local edge = Util.frame({
			Name = "Edge",
			Position = UDim2.fromOffset(1, 1),
			Size = UDim2.new(1, -2, 1, -2),
			ZIndex = 50,
			Parent = body,
		})
		Util.corner(edge, math.max(radius - 1, 0))
		Util.glassStroke(ctx, edge, opts.EdgeToken or "BorderStrong", opts.EdgeTransparency or 0.15)

		local sheen = Util.sheen(body, radius + 4, 0.88)
		sheen.ZIndex = 51
		ctx:RegisterGloss(sheen)

		local surface = {
			Holder = holder,
			Body = body,
			Fill = fill,
			Edge = edge,
			Shadows = shadows,
		}

		function surface.SetAlpha(alpha, preset)
			Motion.tween(body, preset or "Normal", { GroupTransparency = alpha })
			for _, shadow in ipairs(shadows) do
				local target = 1 - (1 - shadowAlpha) * (1 - alpha)
				Motion.tween(shadow, preset or "Normal", { BackgroundTransparency = target })
			end
		end

		return surface
	end

	return Util
end

