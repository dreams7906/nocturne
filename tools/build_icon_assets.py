"""Build the Luau icon asset map from the uploaded-image manifest."""

import json
from pathlib import Path
import struct

ROOT = Path(__file__).resolve().parent.parent
DIRECTORY = ROOT / "assets" / "generated-icons"


def main():
    manifest = json.loads((DIRECTORY / "manifest.json").read_text())
    assets = manifest["assets"]
    atlas = manifest["controls"]
    width, height = struct.unpack(">II", (DIRECTORY / "controls.png").read_bytes()[16:24])
    lines = ["-- Generated by tools/build_icon_assets.py from assets/generated-icons/manifest.json.", "local Assets = {}"]
    for name, asset_id in assets.items():
        if name != "controls":
            lines.append(f'Assets.{name} = {{ Image = "rbxassetid://{asset_id}" }}')
    lines.append(f'local sheet = "rbxassetid://{assets["controls"]}"')
    lines.append(f"local size = Vector2.new({width}, {height})")
    lines.append(f'local cell = Vector2.new(size.X / {atlas["columns"]}, size.Y / {atlas["rows"]})')
    names = ", ".join(json.dumps(name) for name in atlas["names"])
    lines.append(f"for index, name in ipairs({{ {names} }}) do")
    lines.append("\tAssets[name] = {")
    lines.append("\t\tImage = sheet,")
    lines.append(f'\t\tRectOffset = Vector2.new((index - 1) % {atlas["columns"]} * cell.X, math.floor((index - 1) / {atlas["columns"]}) * cell.Y),')
    lines.append("\t\tRectSize = cell, SheetSize = size,")
    lines.append("\t}")
    lines.append("end")
    lines.append("return Assets")
    (ROOT / "src" / "Nocturne" / "Icons" / "Assets.luau").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"Mapped {len(assets) - 1 + len(atlas['names'])} icons to {len(assets)} uploaded images")


if __name__ == "__main__":
    main()
