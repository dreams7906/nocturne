"""
Bundles the modular src/Nocturne sources into one file,
Nocturne.lua, that returns the Library table.

Each module is wrapped in a function that receives a virtual `script`
node and a `require` that understands those nodes, so the sources keep
using normal paths like require(script.Parent.Core.Util).

Usage:  python tools/bundle.py
"""

from __future__ import annotations

import pathlib
import re
import hashlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "src" / "Nocturne"
OUT = ROOT / "Nocturne.lua"

PRELUDE = r'''--!nocheck
--[[
	Nocturne UI {version}
	Dark glass interface library for Roblox: floating dock, tabbed window,
	themed components, configs. Single-file build of src/ (tools/bundle.py).

	local Library = loadstring(game:HttpGet("https://raw.githubusercontent.com/dreams7906/nocturne/main/Nocturne.lua"))()
	local Window = Library:CreateWindow({{ Title = "Nocturne" }})

	Do not edit this file by hand; edit src/ and run the bundler.
]]

local __modules = {{}}
local __cache = {{}}
local __nodes = {{}}

local __Node = {{}}
__Node.__index = function(node, key)
	local method = rawget(__Node, key)
	if method then
		return method
	end
	local child = node.__children[key]
	if child then
		return child
	end
	error(("%s is not a valid member of %s"):format(tostring(key), node.__path), 2)
end
function __Node.FindFirstChild(node, name)
	return node.__children[name]
end
function __Node.WaitForChild(node, name)
	return node.__children[name]
end
function __Node.GetFullName(node)
	return node.__path
end

local function __node(path)
	local existing = __nodes[path]
	if existing then
		return existing
	end
	local parentPath, name = string.match(path, "^(.*)%.([^%.]+)$")
	local node = setmetatable({{ Name = name or path, __path = path, __children = {{}} }}, __Node)
	if parentPath then
		local parent = __node(parentPath)
		rawset(node, "Parent", parent)
		parent.__children[node.Name] = node
	end
	__nodes[path] = node
	return node
end

local __require
__require = function(target)
	if type(target) ~= "table" or not rawget(target, "__path") then
		return require(target)
	end
	local path = target.__path
	local cached = __cache[path]
	if cached ~= nil then
		return cached
	end
	local loader = __modules[path]
	if not loader then
		error("Nocturne bundle: no module at " .. path, 2)
	end
	local result = loader(target, __require)
	__cache[path] = result
	return result
end
'''

MODULE = '''
__node("{path}")
__modules["{path}"] = function(script, require)
{body}
end
'''

EPILOGUE = '''
return __require(__nodes["Nocturne"])
'''


def module_path(file: pathlib.Path) -> str:
    rel = file.relative_to(SRC.parent).with_suffix("")
    parts = list(rel.parts)
    if parts[-1] == "init":
        parts.pop()
    return ".".join(parts)


def main() -> None:
    files = sorted(SRC.rglob("*.luau"))
    version = "1.0.0"
    init = (SRC / "init.luau").read_text(encoding="utf-8")
    match = re.search(r'Version = "([^"]+)"', init)
    if match:
        version = match.group(1)

    chunks = [PRELUDE.format(version=version)]
    for file in files:
        body = file.read_text(encoding="utf-8").replace("\r\n", "\n").rstrip("\n")
        body = "\n".join(("\t" + line) if line.strip() else "" for line in body.split("\n"))
        # Long-string comments ([[ ]]) must stay unindented-safe; tabs inside
        # comments are harmless, and no source uses multi-line string data.
        chunks.append(MODULE.format(path=module_path(file), body=body))
    chunks.append(EPILOGUE)

    OUT.write_text("".join(chunks), encoding="utf-8", newline="\n")
    lines = sum(chunk.count("\n") for chunk in chunks)
    print(f"Wrote {OUT.name}: {len(files)} modules, {lines} lines, v{version}")

    example = (ROOT / "Example.lua").read_text(encoding="utf-8")
    digest = hashlib.sha256(OUT.read_bytes()).hexdigest()[:12]
    example, count = re.subn(
        r'(local Library = loadstring\(game:HttpGet\("https://raw\.githubusercontent\.com/dreams7906/nocturne/main/Nocturne\.lua)(?:\?v=[0-9a-f]+)?("\)\)\(\))',
        lambda match: f'{match[1]}?v={digest}{match[2]}', example,
    )
    if count != 1:
        raise ValueError("Expected exactly one Nocturne.lua download in Example.lua")
    (ROOT / "Example.lua").write_text(example, encoding="utf-8", newline="\n")
    print("Updated Example.lua library version")


if __name__ == "__main__":
    main()
